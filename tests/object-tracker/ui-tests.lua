-- Preserve previous UI state for hot-reload assertions after a second boot.
Mock.oldGui=gui
function testReloaded()
    assert(Mock.oldGui._destroyed)
    assert(Mock.oldAlertLayer._destroyed,'old alert layer survives reload')
    local fresh=Mock.gui():FindFirstChild('EntityAlerts')
    assert(fresh and not fresh:FindFirstChild('Alert_Rush'))
    assert(Mock.run.Heartbeat:count()==1,'duplicate heartbeat after reload')
    assert(workspace.DescendantAdded:count()==1,'duplicate spawn listener after reload')
    assert(Mock.input.InputBegan:count()==1,'input leak after reload')
    assert(Mock.effects()==1,'effect folder leak after reload')
    assert(#Mock.markers()==0,'old markers survive reload')
    pass('reload stops old tracker and disconnects its signals')
    Mock.findText('Dừng & thoát').Activated:Fire()
    assert(Mock.gui()==nil)
    assert(Mock.run.Heartbeat:count()==0)
    assert(Mock.input.InputBegan:count()==0)
    assert(Mock.input.InputChanged:count()==0)
    assert(Mock.effects()==0)
    assert(workspace.DescendantAdded:count()==0)
    pass('Dừng & thoát removes all effects/connections')
end
function testExternalDestroy()
    assert(Mock.run.Heartbeat:count()==1)
    Mock.gui():Destroy()
    assert(Mock.run.Heartbeat:count()==0)
    assert(Mock.effects()==0)
    assert(workspace.DescendantAdded:count()==0)
    pass('external GUI destruction also tears down tracker')
end
