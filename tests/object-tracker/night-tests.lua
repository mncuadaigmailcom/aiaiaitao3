local passed=0
local function test(name,fn) fn(); passed=passed+1; print('PASS NIGHT '..name) end
local function eq(a,b) assert(a==b,tostring(a)..' ~= '..tostring(b)) end
local props={'Ambient','OutdoorAmbient','Brightness','ExposureCompensation','GlobalShadows','EnvironmentDiffuseScale','EnvironmentSpecularScale'}
local lighting,camera,night,deps,baseline,cameraCalls
local function snapshot()
    local s={}; for _,k in ipairs(props) do s[k]=lighting[k] end; return s
end
local function restored(s) for _,k in ipairs(props) do eq(lighting[k],s[k]) end end
local function effect(class,parent,enabled)
    local e=Mock.node(class,'GameEffect',parent); e.Enabled=enabled; return e
end
local function setup()
    lighting=Mock.node('Lighting','Lighting',nil); camera=Mock.node('Camera','Camera',nil)
    lighting.Ambient=Color3.fromRGB(0,0,0); lighting.OutdoorAmbient=Color3.fromRGB(10,12,15)
    lighting.Brightness=0.2; lighting.ExposureCompensation=-0.8; lighting.GlobalShadows=true
    lighting.EnvironmentDiffuseScale=0.1; lighting.EnvironmentSpecularScale=1
    lighting.ClockTime=2; lighting.FogEnd=250; baseline=snapshot(); cameraCalls=0
    deps={lighting=lighting,getCamera=function() cameraCalls=cameraCalls+1; return camera end,
        createCorrection=function() return Mock.node('ColorCorrectionEffect','TrackerSoftNightVision',lighting) end}
    night=createNightVision(deps)
end
setup()
test('starts disabled without changing lighting or creating an effect',function()
    eq(night.enabled,false); restored(baseline); eq(#lighting:GetChildren(),0); eq(cameraCalls,0)
end)
test('dark-room ambience is lifted moderately rather than using extreme fullbright',function()
    night:setEnabled(true); eq(night.enabled,true); eq(lighting.Brightness,1.2)
    eq(lighting.ExposureCompensation,-0.15); eq(lighting.GlobalShadows,false)
    assert(lighting.Ambient.R>0.3 and lighting.Ambient.R<0.5)
    assert(lighting.OutdoorAmbient.B<0.5); eq(lighting.EnvironmentSpecularScale,0.15)
end)
test('soft correction has small brightness and reduced contrast with no bloom of its own',function()
    local cc=night.correction; eq(cc.Enabled,true); eq(cc.Brightness,0.01)
    assert(cc.Contrast<0 and cc.Contrast> -0.1); assert(cc.TintColor.R>0.9)
    eq(#lighting:GetChildren(),1)
end)
test('clock time, fog and unrelated settings are not modified',function()
    eq(lighting.ClockTime,2); eq(lighting.FogEnd,250)
end)
test('turning off restores every managed property and removes only its own correction',function()
    local cc=night.correction; night:setEnabled(false); restored(baseline)
    assert(cc._destroyed); eq(#lighting:GetChildren(),0)
end)
test('repeated enable is idempotent and does not overwrite the original snapshot',function()
    setup(); night:setEnabled(true); local cc=night.correction
    night:setEnabled(true); eq(night.correction,cc); eq(#lighting:GetChildren(),1)
    night:setEnabled(false); restored(baseline)
end)
test('existing bloom sun rays and grading are suspended but depth of field is untouched',function()
    setup(); local bloom=effect('BloomEffect',lighting,true); local sun=effect('SunRaysEffect',camera,true)
    local grade=effect('ColorCorrectionEffect',lighting,true); local depth=effect('DepthOfFieldEffect',camera,true)
    night:setEnabled(true); eq(bloom.Enabled,false); eq(sun.Enabled,false); eq(grade.Enabled,false); eq(depth.Enabled,true)
    night:setEnabled(false); eq(bloom.Enabled,true); eq(sun.Enabled,true); eq(grade.Enabled,true)
    assert(not bloom._destroyed and not grade._destroyed)
end)
test('effects that were already disabled stay disabled after toggling off',function()
    setup(); local bloom=effect('BloomEffect',lighting,false)
    night:setEnabled(true); night:setEnabled(false); eq(bloom.Enabled,false)
end)
test('new Lighting and Camera effects are picked up on the next scheduled update',function()
    setup(); night:setEnabled(true)
    local a=effect('BloomEffect',lighting,true); local b=effect('SunRaysEffect',camera,true)
    night:step(0.25); eq(a.Enabled,false); eq(b.Enabled,false)
    night:setEnabled(false); eq(a.Enabled,true); eq(b.Enabled,true)
end)
test('changing camera restores old-camera effects and handles new-camera effects',function()
    setup(); local old=effect('BloomEffect',camera,true); night:setEnabled(true); eq(old.Enabled,false)
    camera=Mock.node('Camera','NewCamera',nil); local new=effect('BloomEffect',camera,true)
    night:step(0.25); eq(old.Enabled,true); eq(new.Enabled,false)
    night:setEnabled(false); eq(new.Enabled,true)
end)
test('unparenting an effect while camera is missing restores it and releases the reference',function()
    setup(); local a=effect('BloomEffect',lighting,true); night:setEnabled(true)
    a.Parent=nil; camera=nil; night:step(0.25); eq(a.Enabled,true); eq(night.effects[a],nil)
end)
test('game lighting changes observed while active are remembered for restoration',function()
    setup(); night:setEnabled(true); lighting.Brightness=0.8; lighting.ExposureCompensation=-0.4
    night:step(0.25); eq(lighting.Brightness,1.2); night:setEnabled(false)
    eq(lighting.Brightness,0.8); eq(lighting.ExposureCompensation,-0.4)
end)
test('a game change immediately before off is preserved instead of overwritten',function()
    setup(); night:setEnabled(true); lighting.Brightness=2.5; night:setEnabled(false); eq(lighting.Brightness,2.5)
end)
test('a game effect re-enabled while active is restored to the observed enabled state',function()
    setup(); local bloom=effect('BloomEffect',lighting,false); night:setEnabled(true)
    bloom.Enabled=true; night:step(0.25); eq(bloom.Enabled,false)
    night:setEnabled(false); eq(bloom.Enabled,true)
end)
test('effect tracking is capped and child enumeration is processed in bounded batches',function()
    setup(); local all={}; for i=1,200 do all[i]=effect('BloomEffect',lighting,true) end
    night:setEnabled(true); eq(night.effectCount,64)
    night:step(0.25); eq(night.effectCount,128)
    for i=1,8 do night:step(0.25) end; eq(night.effectCount,128)
    night:setEnabled(false); for _,e in ipairs(all) do eq(e.Enabled,true) end
end)
test('scheduled updates do not run every frame and disabled updates do no work',function()
    setup(); night:step(10); eq(cameraCalls,0); night:setEnabled(true); cameraCalls=0
    night:step(0.1); night:step(0.1); eq(cameraCalls,0); night:step(0.05); eq(cameraCalls,1)
end)
test('invalid delta values do not update lighting',function()
    setup(); night:setEnabled(true); cameraCalls=0
    for _,dt in ipairs({-1,0/0,math.huge,'bad'}) do night:step(dt) end; eq(cameraCalls,0)
end)
test('failed enable rolls back lighting and exposes the error without throwing',function()
    setup(); deps.createCorrection=function() error('injected creation failure') end
    local ok,err=night:setEnabled(true); eq(ok,false); assert(err:find('injected creation failure',1,true))
    restored(baseline); eq(night.enabled,false); eq(#lighting:GetChildren(),0)
end)
test('external removal of the local correction is recovered without accumulating effects',function()
    setup(); night:setEnabled(true); local old=night.correction; old:Destroy()
    night:step(0.25); assert(night.correction~=old); eq(#lighting:GetChildren(),1)
end)
test('plain camera fallback and missing camera are safe',function()
    setup(); camera={CFrame={}}; night:setEnabled(true); night:step(0.25)
    camera=nil; night:step(0.25); night:setEnabled(false); restored(baseline)
end)
test('bright-scene settings are restrained as well as restored, not added to blindly',function()
    setup(); lighting.Brightness=4; lighting.ExposureCompensation=1.5; baseline=snapshot()
    night:setEnabled(true); eq(lighting.Brightness,1.2); eq(lighting.ExposureCompensation,-0.15)
    night:setEnabled(false); restored(baseline)
end)
test('destroy restores effects and lighting once and cannot be restarted',function()
    setup(); local bloom=effect('BloomEffect',lighting,true); night:setEnabled(true)
    night:destroy(); night:destroy(); restored(baseline); eq(bloom.Enabled,true)
    eq(night:setEnabled(true),false); eq(#lighting:GetChildren(),1)
end)
print(passed..' soft night-vision core tests passed')
