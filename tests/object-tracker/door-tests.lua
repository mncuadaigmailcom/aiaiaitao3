local passed=0
local function test(name,fn) fn(); passed=passed+1; print('PASS DOORS '..name) end
local function eq(a,b) assert(a==b,tostring(a)..' ~= '..tostring(b)) end
local root,doors,origin,players,created,removed,deps
local function setup()
    root=Mock.node('Workspace','DoorFixture',nil); origin=Vector3.new(0,0,0)
    players={list={}}; function players:GetPlayers() return self.list end
    created,removed=0,0
    deps={root=root,players=players,now=function() return 0 end,getOrigin=function() return origin end,
        createMarker=function(hit) created=created+1; return {hit=hit} end,
        removeMarker=function(m) m.removed=true; removed=removed+1 end,
        updateMarker=function(m,hit,state) m.hit=hit; m.state=state end}
    doors=createDoorTracker(deps)
end
local function door(n,x,parent,name) return Mock.node('Part',name or 'doors '..n,parent or root,x or n*20) end
local function settle(n) for _=1,n or 24 do doors:step(1/60) end end
local function numbers()
    local out={}; for _,h in ipairs(doors.list) do out[#out+1]=h.number end
    return table.concat(out,',')
end
setup()
test('disabled by default with an independent numbered index',function()
    eq(doors.enabled,false); eq(doors.current,1); eq(#doors.list,0)
    eq(doors.showBox,true); eq(doors.showLabel,true); eq(doors.throughWalls,true)
end)
test('strict door names accept spaced compact underscored dashed and zero-padded aliases',function()
    for _,s in ipairs({'doors 1','Doors001','DOOR_0001','Door-1',' door 1 '}) do
        eq(doors.numberOf(Mock.node('Part',s,root,0)),1)
    end
    for _,s in ipairs({'doors 0','doors 2001','doors -1','doors 1.5','trapdoor1','doors 1 fake','1','doors 1e2'}) do
        eq(doors.numberOf(Mock.node('Part',s,root,0)),nil)
    end
end)
test('generic Door under numbered room is supported, unrelated numeric objects are not',function()
    local room=Mock.node('Model','0040',root)
    eq(doors.numberOf(Mock.node('Model','Door',room)),40)
    room.Name='Room_40'; eq(doors.numberOf(room:FindFirstChild('Door')),40)
    room.Name='Storage'; eq(doors.numberOf(room:FindFirstChild('Door')),nil)
end)
test('starts at door 1 and renders only the initial numeric neighbourhood',function()
    setup(); for n=1,6 do door(n) end
    doors:setEnabled(true); settle(); eq(doors.current,1); eq(numbers(),'1,2')
end)
test('missing door 1 skips to the first existing number without a character',function()
    setup(); origin=nil; door(50); door(7); door(8)
    doors:setEnabled(true); settle(); eq(doors.current,7); eq(numbers(),'7,8')
end)
test('startup without a character keeps searching lower numbers as more doors stream in',function()
    setup(); origin=nil; door(50); doors:setEnabled(true); settle(); eq(doors.current,50)
    local earlier=door(2); doors:notifyAdded(earlier); doors:step(1/60); eq(doors.current,2)
end)
test('standing at door 40 shows only 39,40,41 and never every passed door',function()
    setup(); for n=1,100 do door(n) end; origin=Vector3.new(800,0,0)
    doors:setEnabled(true); settle(); eq(doors.current,40); eq(numbers(),'39,40,41')
    assert(not doors.items[38] and not doors.items[42])
end)
test('walking backwards to door 39 switches to 38,39,40',function()
    origin=Vector3.new(780,0,0); settle(); eq(doors.current,39); eq(numbers(),'38,39,40')
    assert(not doors.items[41])
end)
test('crossing door 1 advances to 2 immediately and does not oscillate while still near 1',function()
    setup(); for n=1,5 do door(n) end
    origin=Vector3.new(19,0,0); doors:setEnabled(true); settle(); eq(doors.current,1)
    origin=Vector3.new(21,0,0); doors:step(1/60); eq(doors.current,2); eq(numbers(),'1,2,3')
    settle(); eq(doors.current,2)
end)
test('reverse crossing reactivates earlier doors and removes the new far-behind side',function()
    origin=Vector3.new(40,0,0); settle(); eq(doors.current,2)
    origin=Vector3.new(39,0,0); doors:step(1/60); eq(doors.current,1); eq(numbers(),'1,2')
end)
test('crossing door 40 forward removes door 39; reversing restores it and earlier context',function()
    setup(); for n=37,43 do door(n) end; origin=Vector3.new(800,0,0)
    doors:setEnabled(true); settle(); eq(numbers(),'39,40,41')
    origin=Vector3.new(801,0,0); doors:step(1/60); eq(doors.current,41); eq(numbers(),'40,41,42')
    origin=Vector3.new(799,0,0); doors:step(1/60); eq(doors.current,39); eq(numbers(),'38,39,40')
end)
test('sequential traversal through 40 doors and back keeps the three-door window without leaks',function()
    setup(); for n=1,42 do door(n) end; origin=Vector3.new(20,0,0)
    doors:setEnabled(true); settle()
    for n=1,40 do
        origin=Vector3.new(n*20,0,0); doors:step(1/60); eq(doors.current,n)
        origin=Vector3.new(n*20+1,0,0); doors:step(1/60); eq(doors.current,n+1)
        assert(created-removed<=3)
    end
    for n=40,2,-1 do
        origin=Vector3.new(n*20,0,0); doors:step(1/60); eq(doors.current,n)
        origin=Vector3.new(n*20-1,0,0); doors:step(1/60); eq(doors.current,n-1)
        assert(created-removed<=3)
    end
end)
test('crossing while the next door is unstreamed waits at the next index then skips missing numbers',function()
    setup(); door(38); door(39); origin=Vector3.new(780,0,0)
    doors:setEnabled(true); settle(); eq(doors.current,39)
    origin=Vector3.new(781,0,0); doors:step(1/60); eq(doors.current,40); eq(numbers(),'39')
    settle(); eq(doors.current,40)
    local future=door(41); doors:notifyAdded(future); doors:step(1/60)
    eq(doors.current,41); eq(numbers(),'41')
end)
test('an isolated first door can use its facing plane until numbered neighbours stream in',function()
    setup(); local first=door(1); first.CFrame={LookVector=Vector3.new(1,0,0)}
    origin=Vector3.new(20,0,0); doors:setEnabled(true); settle()
    origin=Vector3.new(21,0,0); doors:step(1/60); eq(doors.current,2)
    origin=Vector3.new(19,0,0); doors:step(1/60); eq(doors.current,1)
end)
test('sparse numbers skip missing doors when crossing but the visible window stays numeric ±1',function()
    setup(); door(1); door(7); door(8); origin=Vector3.new(19,0,0)
    doors:setEnabled(true); settle(); origin=Vector3.new(21,0,0); doors:step(1/60)
    eq(doors.current,7); eq(numbers(),'7,8')
end)
test('upper boundary includes door 2000 but never creates door 2001',function()
    setup(); door(1998); door(1999); door(2000); door(2001); origin=Vector3.new(40000,0,0)
    doors:setEnabled(true); settle(); eq(doors.current,2000); eq(numbers(),'1999,2000')
    eq(doors.byNumber[2001],nil)
end)
test('teleport across a 2000-door fixture converges without permanent monotonic progress',function()
    setup(); for n=1,2000 do door(n) end
    doors:setEnabled(true); settle(30); eq(doors.current,1)
    origin=Vector3.new(39980,0,0); settle(30); eq(doors.current,1999); eq(numbers(),'1998,1999,2000')
    origin=Vector3.new(800,0,0); settle(30); eq(doors.current,40); eq(numbers(),'39,40,41')
    assert(created-removed<=3)
end)
test('door index traversal is capped rather than scanning 2000 candidates per tick',function()
    setup(); doors.scanBudget=5; doors.nearestBudget=7
    for n=1,300 do door(n) end; doors:setEnabled(true); doors:step(1/60)
    eq(doors.visited,5); assert(doors.stack); eq(doors.cursor,8); assert(#doors.list<=3)
end)
test('newly spawned numbered door uses bounded event path before a slow scan reaches it',function()
    setup(); for n=1,100 do Mock.node('Part','Decoration',root,n) end
    doors.scanBudget=1; doors:setEnabled(true)
    local target=door(40,0); doors:notifyAdded(target); doors:step(1/60)
    eq(doors.current,40); eq(doors.list[1].inst,target); eq(doors.visited,1)
end)
test('Model door with nested panels produces one marker and prefers PrimaryPart',function()
    setup(); local m=Mock.node('Model','doors 1',root)
    local primary=Mock.node('Part','Panel',m,20); m.PrimaryPart=primary
    Mock.node('Part','doors 1',m,21)
    doors:setEnabled(true); settle(); eq(#doors.list,1); eq(doors.list[1].inst,m); eq(doors.list[1].part,primary)
end)
test('door Model without a part becomes locatable after its panel arrives',function()
    setup(); local m=Mock.node('Model','Doors 3',root)
    doors:setEnabled(true); settle(); eq(#doors.list,0)
    local part=Mock.node('Part','Panel',m,3); doors:notifyAdded(part); doors:step(1/60)
    eq(doors.current,3); eq(#doors.list,1)
end)
test('removal clears obsolete marker; same-number replacement rebinds safely',function()
    setup(); local old=door(1); door(2); doors:setEnabled(true); settle()
    local marker=doors.items[1].marker; old:Destroy(); doors:step(1/60); assert(marker.removed)
    local replacement=door(1); doors:notifyAdded(replacement); settle()
    eq(doors.items[1].hit.inst,replacement)
end)
test('renaming a door invalidates old number and periodic scan discovers the new name',function()
    setup(); local target=door(1); doors:setEnabled(true); settle(); target.Name='doors 10'
    settle(180); eq(doors.current,10); eq(numbers(),'10'); eq(doors.byNumber[1],nil)
end)
test('closest same-number duplicate wins while keeping the index bounded to 2000 slots',function()
    setup(); door(1,200); local nearby=door(1,20)
    doors:setEnabled(true); settle(); eq(#doors.list,1); eq(doors.list[1].inst,nearby)
end)
test('character-owned doors and effect descendants are excluded',function()
    setup(); local char=Mock.node('Model','Character',root); players.list={{Character=char}}
    door(1,0,char); local effects=Mock.node('Folder','Effects',root); door(2,0,effects)
    deps.ignore=function(inst) return inst==effects or inst:IsDescendantOf(effects) end
    door(3); doors:setEnabled(true); settle(); eq(doors.current,3); eq(numbers(),'3')
end)
test('losing character origin freezes the current door instead of following the camera',function()
    setup(); for n=1,50 do door(n) end; origin=Vector3.new(800,0,0)
    doors:setEnabled(true); settle(); eq(doors.current,40)
    origin=nil; settle(50); eq(doors.current,40); eq(numbers(),'39,40,41'); eq(doors.list[1].distance,nil)
end)
test('queue is deduplicated, capped and requests a fallback scan on overflow',function()
    setup(); doors:setEnabled(true); doors.queueLimit=4
    local target=door(1); doors:notifyAdded(target); doors:notifyAdded(target); eq(doors.tail,1)
    for n=2,20 do doors:notifyAdded(door(n)) end
    eq(doors.tail,4); eq(doors.rescan,true)
    doors.eventBudget=2; doors:step(1/60); eq(doors.head,3)
end)
test('time deadline can yield both scan and nearest work before quotas are exhausted',function()
    setup(); local time=0; deps.now=function() time=time+0.002; return time end
    door(1); doors=createDoorTracker(deps); doors:setEnabled(true); doors:step(1/60)
    eq(doors.visited,0); eq(doors.cursor,1); assert(doors.stack)
end)
test('invalid delta times and nonfinite origins do not move state or throw',function()
    setup(); door(1); doors:setEnabled(true)
    for _,dt in ipairs({-1,0/0,math.huge,'bad'}) do doors:step(dt) end
    eq(doors.visited,0); origin=Vector3.new(0/0,0,0); settle(); eq(doors.origin,nil)
end)
test('door state never mutates an independent entity engine or enables new alert kinds',function()
    setup(); local entity=createTracker(deps); entity:setQuery('Chest'); entity:setEnabled(true)
    local alerts=entity.alerts.enabled
    door(1); doors:setEnabled(true); settle(); doors:setEnabled(false)
    eq(entity.enabled,true); eq(entity.query,'Chest'); eq(entity.alerts.enabled,alerts)
    eq(#entity.presets,23)
end)
test('disable, resume, destroy and repeated destroy clean all door resources only',function()
    setup(); door(1); door(2); doors:setEnabled(true); settle(); assert(created>0)
    doors:setEnabled(false); eq(#doors.list,0); eq(next(doors.items),nil); eq(created,removed)
    doors:setEnabled(true); settle(); eq(numbers(),'1,2')
    doors:destroy(); doors:destroy(); eq(created,removed); eq(next(doors.byNumber),nil)
    eq(doors:setEnabled(true),false)
end)
print(passed..' numbered-door core tests passed')
